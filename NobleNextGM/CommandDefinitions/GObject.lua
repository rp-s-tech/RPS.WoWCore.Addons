local _, ns = ...

local function withGobAlias(pathTokens, extraAliases)
    local alias = { "gob" }
    for i = 2, #pathTokens do
        alias[#alias + 1] = pathTokens[i]
    end
    local aliases = { alias }
    if extraAliases then
        for i = 1, #extraAliases do
            aliases[#aliases + 1] = extraAliases[i]
        end
    end
    return aliases
end

